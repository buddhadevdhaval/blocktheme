<?php
/**
 * Render: Additional Links Block
 *
 * @param array    $attributes The block attributes.
 * @param string   $content    The block content.
 * @param WP_Block $block      The block instance.
 *
 * @package ambrygen
 */

use Ambrygen\Theme\Core\Helper;

defined( 'ABSPATH' ) || exit;

$ambrygen_attributes  = is_array( $attributes ) ? $attributes : array();
$ambrygen_block_id    = isset( $ambrygen_attributes['blockId'] ) ? sanitize_html_class( $ambrygen_attributes['blockId'] ) : '';
$ambrygen_heading     = $ambrygen_attributes['heading'] ?? '';
$ambrygen_heading_tag = Helper::get_heading_tag( $ambrygen_attributes['headingTag'] ?? 'h2', 'h2' );
$ambrygen_description = $ambrygen_attributes['description'] ?? '';
$ambrygen_content     = $content ?? '';
$ambrygen_has_heading = '' !== trim( wp_strip_all_tags( $ambrygen_heading ) );
$ambrygen_has_desc    = '' !== trim( wp_strip_all_tags( $ambrygen_description ) );
$wrapper_attributes   = get_block_wrapper_attributes(
	array_filter(
		array(
			'id'    => $ambrygen_block_id ?: null,
			'class' => 'additional-links block-layout',
		)
	)
);
?>

<div <?php echo $wrapper_attributes; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_block_wrapper_attributes(). ?>>
	<div class="careers-highlight__header block__rowflex">
		<?php if ( $ambrygen_has_heading ) : ?>
			<div class="block__rowflex--col-left">
			<<?php echo tag_escape( $ambrygen_heading_tag ); ?> class="careers-highlight__title block__rowflex--heading-title heading-4 mb-0 js-gsap-fade block-title">
				<?php echo wp_kses( $ambrygen_heading, Helper::allowed_heading_html() ); ?>
			</<?php echo tag_escape( $ambrygen_heading_tag ); ?>>
		</div>
		<?php endif; ?>

		<?php if ( $ambrygen_has_desc ) : ?>
			<div class="careers-highlight__intro block__rowflex--block-content subtitle1-reg js-gsap-fade block-description">
				<?php echo wp_kses_post( $ambrygen_description ); ?>
			</div>
		<?php endif; ?>
	</div>
	<div class="is-style-gl-s50"></div>
	<div class="additional-link__cards">
		<?php
		// InnerBlocks content is pre-escaped by WordPress block rendering and considered safe here.
		echo $ambrygen_content; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
		?>
	</div>
</div>
