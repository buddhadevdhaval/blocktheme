<?php
/**
 * Render: Tab Menu Block
 *
 * @param array    $attributes The block attributes.
 * @param string   $content    The block content.
 * @param WP_Block $block      The block instance.
 *
 * @package ambrygen
 */

defined( 'ABSPATH' ) || exit;

$ambrygen_attributes    = is_array( $attributes ) ? $attributes : array();
$ambrygen_block_id      = isset( $ambrygen_attributes['blockId'] ) ? sanitize_html_class( $ambrygen_attributes['blockId'] ) : '';
$ambrygen_tabs          = $ambrygen_attributes['tabs'] ?? array();
$ambrygen_scroll_offset = 250;
$ambrygen_tab_behavior  = $ambrygen_attributes['tabBehavior'] ?? 'scroll';

if ( ! is_array( $ambrygen_tabs ) ) {
	$ambrygen_tabs = array();
}

$ambrygen_wrapper_attributes = get_block_wrapper_attributes(
	array_filter(
		array(
			'class'             => 'secondary-sticky-tabs',
			'id'                => $ambrygen_block_id ? $ambrygen_block_id : null,
			'data-offset'       => (string) $ambrygen_scroll_offset,
			'data-tab-behavior' => in_array( $ambrygen_tab_behavior, array( 'scroll', 'tab-mode' ), true ) ? $ambrygen_tab_behavior : 'scroll',
		)
	)
);
?>

<div <?php echo $ambrygen_wrapper_attributes; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_block_wrapper_attributes(). ?>>
	<div class="horizontal-tabs" role="tablist">
			<?php foreach ( $ambrygen_tabs as $index => $tab_item ) : ?>
				<?php
				if ( ! is_array( $tab_item ) ) {
					continue;
				}

				$label       = $tab_item['label'] ?? '';
				$target      = $tab_item['targetId'] ?? '';
				$is_active   = ! empty( $tab_item['isActive'] );
				$button_text = $label ? $label : $target;
				?>
				<button
					type="button"
					class="tab-button tab-menu-section__tab<?php echo $is_active ? ' active' : ''; ?>"
					data-scroll-target="<?php echo esc_attr( $target ); ?>"
					aria-selected="<?php echo esc_attr( $is_active ? 'true' : 'false' ); ?>"
				>
					<?php echo esc_html( $button_text ); ?>
				</button>
			<?php endforeach; ?>
	</div>
</div>
