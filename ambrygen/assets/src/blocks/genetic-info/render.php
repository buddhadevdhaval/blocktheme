<?php
/**
 * Render: Genetic Info Block
 *
 * @param array    $attributes The block attributes.
 * @param string   $content    The block content.
 * @param WP_Block $block      The block instance.
 *
 * @package ambrygen
 */

use Ambrygen\Theme\Core\Helper;

	// Block attributes.
	$ambrygen_attributes       = $attributes ?? array();
	$ambrygen_block_id         = $ambrygen_attributes['blockId'] ?? '';
	$ambrygen_link             = isset( $ambrygen_attributes['link'] ) && is_array( $ambrygen_attributes['link'] )
	? $ambrygen_attributes['link']
	: array();
	$ambrygen_heading          = $ambrygen_attributes['heading'] ?? '';
	$ambrygen_heading_tag      = $ambrygen_attributes['headingTag'] ?? 'h2';
	$ambrygen_description      = $ambrygen_attributes['description'] ?? '';
	$ambrygen_show_description = isset( $ambrygen_attributes['showDescription'] ) ? (bool) $ambrygen_attributes['showDescription'] : true;
	$ambrygen_video_url        = $ambrygen_attributes['videoUrl'] ?? '';
	$ambrygen_video_type       = $ambrygen_attributes['videoType'] ?? 'embed';
	$ambrygen_iframe_url       = $ambrygen_attributes['iframeUrl'] ?? '';
	$ambrygen_image_url        = $ambrygen_attributes['imageUrl'] ?? '';
	$ambrygen_image_id         = absint( $ambrygen_attributes['imageId'] ?? 0 );
	$ambrygen_show_image       = ! empty( $ambrygen_attributes['showImage'] );
	$ambrygen_is_header_vertical = ! empty( $ambrygen_attributes['isHeaderVertical'] );

	$ambrygen_poster_image = isset( $ambrygen_attributes['posterImage'] ) && is_array( $ambrygen_attributes['posterImage'] )
	? $ambrygen_attributes['posterImage']
	: array();

	$ambrygen_poster_image_id = isset( $ambrygen_poster_image['id'] )
	? (int) $ambrygen_poster_image['id']
	: 0;

	$ambrygen_poster_url = isset( $ambrygen_poster_image['url'] )
	? esc_url( $ambrygen_poster_image['url'] )
	: '';

	$ambrygen_iframe_src = Helper::get_iframe_src( $ambrygen_iframe_url );

	// Determine iframe source.

	// Extract URLs from image objects.
	$ambrygen_wrapper_attributes = get_block_wrapper_attributes(
		$ambrygen_block_id
		? array(
			'class' => 'features-media',
			'id'    => $ambrygen_block_id,
		)
		: array(
			'class' => 'features-media',
		)
	);
	$ambrygen_play_icon_src      = get_theme_file_uri( 'assets/src/images/play-icon.svg' );
	$ambrygen_pause_icon_src     = get_theme_file_uri( 'assets/src/images/pause-icon.svg' );
	$ambrygen_link_target        = ! empty( $ambrygen_link['target'] )
	? esc_attr( $ambrygen_link['target'] )
	: '_self';

	?>

<div <?php echo $ambrygen_wrapper_attributes; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_block_wrapper_attributes(). ?>>
	<div class="features-media__header block__rowflex is-<?php echo $ambrygen_is_header_vertical ? 'vertical' : 'horizontal'; ?>">
		<<?php echo esc_html( $ambrygen_heading_tag ); ?> class="block-title block__rowflex--heading-title heading-2 mb-0 js-gsap-fade">
				<?php
					echo wp_kses(
						$ambrygen_heading,
						Helper::allowed_heading_html()
					);
					?>
		</<?php echo esc_html( $ambrygen_heading_tag ); ?>>
		<?php if ( $ambrygen_show_description && $ambrygen_description ) : ?>
		<div class="block__rowflex--block-content subtitle1-reg js-gsap-fade">
			<p><?php echo wp_kses_post( $ambrygen_description ); ?></p>
			<?php if ( ! empty( $ambrygen_link ) && ! empty( $ambrygen_link['text'] ) && ! empty( $ambrygen_link['url'] ) ) : ?>
			<div class="block_rowflex-link js-gsap-fade">
				<a
					href="<?php echo esc_url( $ambrygen_link['url'] ); ?>"
					class="site-btn is-style-site-text-btn has-icon"
					target="<?php echo esc_attr( $ambrygen_link_target ); ?>"
					<?php echo( '_blank' === $ambrygen_link_target ) ? 'rel="noopener noreferrer"' : ''; ?>
				>
					<?php echo esc_html( $ambrygen_link['text'] ); ?>
				</a>
			</div>
		<?php endif; ?>
		</div>
		<?php endif; ?>
		
	</div>

	<div class="is-style-gl-s50" aria-hidden="true"></div>

	<!-- <div class="features-media__video media_video"> -->
	<?php if ( $ambrygen_show_image ) : ?>
		<div class="features-media has-image js-gsap-fade">
			<?php
				echo Helper::image_with_placeholder( // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
					$ambrygen_image_id,
					'full',
					array(
						'class'   => 'features-media__image',
						'loading' => 'lazy',
					)
				);

			?>
		</div>
	<?php endif; ?>
	<?php if ( ! $ambrygen_show_image && ( ( 'embed' === $ambrygen_video_type && $ambrygen_iframe_src ) || ( 'mp4' === $ambrygen_video_type && $ambrygen_video_url ) ) ) : ?>

	<div class="features-media__video media_video js-gsap-fade">
		<?php if ( ! $ambrygen_show_image && 'embed' === $ambrygen_video_type && $ambrygen_iframe_src ) : ?>
			<div class="features-media__video-wrapper features-media__video-wrapper--iframe">
					<iframe
						src="<?php echo esc_url( $ambrygen_iframe_src ); ?>"
						title="<?php esc_attr_e( 'Genetic testing video', 'ambrygen' ); ?>"
						allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture"
						allowfullscreen
						class="features-media__iframe"
					></iframe>

					<div class="play-icon-video">
							<div class="play-icon circle-icon">
								<img src="<?php echo esc_url( $ambrygen_play_icon_src ); ?>" class="play-icon__img" alt="Play Icon">
							</div>
							<div class="pause-icon circle-icon">
								<img src="<?php echo esc_url( $ambrygen_pause_icon_src ); ?>" class="pause-icon__img" alt="Pause Icon">
							</div>
					</div>
			</div>
		<?php endif; ?>

		<?php if ( ! $ambrygen_show_image && 'mp4' === $ambrygen_video_type && $ambrygen_video_url ) : ?>
			<div class="features-media__video-wrapper">
				<video
					class="videos"
					playsinline
					muted
					preload="metadata"
					loop
					poster="<?php echo esc_url( $ambrygen_poster_url ); ?>"
					controls
				>
					<source src="<?php echo esc_url( $ambrygen_video_url ); ?>" type="video/mp4">
					<?php esc_html_e( 'Your browser does not support the video tag.', 'ambrygen' ); ?>
				</video>

					<div class="play-icon-video">
							<div class="play-icon circle-icon">
								<img src="<?php echo esc_url( $ambrygen_play_icon_src ); ?>" class="play-icon__img" alt="Play Icon">
							</div>
							<div class="pause-icon circle-icon">
								<img src="<?php echo esc_url( $ambrygen_pause_icon_src ); ?>" class="pause-icon__img" alt="Pause Icon">
							</div>
					</div>
			</div>
		<?php endif; ?>
	</div>
	<?php endif; ?>
</div>
